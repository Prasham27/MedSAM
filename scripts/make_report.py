import os, sys; from pathlib import Path
os.environ.setdefault("KMP_DUPLICATE_LIB_OK", "TRUE")
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import json, re
import numpy as np
import pandas as pd
from scipy.stats import wilcoxon
from data.common import get_logger
from evaluation.metrics import wilcoxon_table

TAB, FIG = ROOT / "results/tables", ROOT / "results/figures"
ORDER = ["sam", "unet", "deeplab", "medsam", "lora", "yolo_medsam", "medsam_point"]
MAIN = ["dsc3d", "nsd3d", "dsc3d_pp", "nsd3d_pp", "slice_dsc_mean", "sec_per_slice"]


def order(ms):
    return [m for m in ORDER if m in ms] + sorted(m for m in ms if m not in ORDER)


def md(df):
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join("" if pd.isna(v) else str(v) for v in r) + " |" for r in df.values]
    return "\n".join(lines)


def main():
    log = get_logger("make_report", "all").info
    df = pd.read_csv(TAB / "benchmark.csv")
    df["tag"] = df["tag"].fillna("").astype(str)
    main_rows = df[(df.tag == "") & (df.jitter == 0)]
    parts = ["# REPORT - MedSAM MSD evaluation", "",
             "Generated by `scripts/make_report.py` from `results/tables/` and `results/figures/`. "
             "Per-volume metrics; median [IQR] = median [25th-75th percentile] over test volumes. "
             "Jitter 0 = GT-derived box with no perturbation."]

    # 1. dataset
    ds = TAB / "dataset_stats.csv"
    parts += ["", "## 1. Dataset statistics",
              md(pd.read_csv(ds)) if ds.exists() else "dataset_stats.csv missing."]

    # 2. median [IQR]
    rows = []
    for (task, target), g in main_rows.groupby(["task", "target"]):
        for m in order(list(g.method.unique())):
            s = g[g.method == m]
            row = {"task": task, "target": target, "method": m, "n_volumes": s.volume.nunique()}
            for c in MAIN:
                q1, q2, q3 = s[c].quantile([0.25, 0.5, 0.75])
                row[c] = f"{q2:.3f} [{q1:.3f}-{q3:.3f}]"
            rows.append(row)
    parts += ["", "## 2. Median [IQR] per task/target/method (jitter 0)",
              md(pd.DataFrame(rows)) if rows else "No jitter-0 rows."]

    # 3. Wilcoxon (ref = medsam)
    wrows = []
    for (task, target), g in main_rows.groupby(["task", "target"]):
        if "medsam" not in set(g.method):
            continue
        others = [m for m in order(list(g.method.unique())) if m != "medsam"]
        for metric in ["dsc3d", "nsd3d"]:
            w = wilcoxon_table(g, metric, others, "medsam")
            w.insert(0, "target", target)
            w.insert(0, "task", task)
            wrows.append(w)
    wil = pd.concat(wrows, ignore_index=True) if wrows else pd.DataFrame(
        columns=["task", "target", "method", "ref_method", "metric", "n_pairs", "p_value"])
    wil.to_csv(TAB / "wilcoxon.csv", index=False)
    parts += ["", "## 3. Wilcoxon signed-rank tests vs MedSAM (two-sided, paired by volume)",
              md(wil.round({"p_value": 4})) if len(wil) else "No pairs available.",
              "", "Note: with few volumes (n_pairs small) the exact two-sided p-value has a floor (n=3 -> p>=0.25); "
                  "read these as descriptive."]

    # 3b. pooled Wilcoxon over all 11 test volumes (ref = medsam), keyed by task/target/volume
    key = main_rows.assign(key=main_rows.task + "/" + main_rows.target + "/" + main_rows.volume)
    pooled = []
    for metric in ["dsc3d", "nsd3d"]:
        wide = key.pivot_table(index="key", columns="method", values=metric, aggfunc="first")
        for m in ["sam", "unet", "deeplab", "lora"]:
            if m not in wide or "medsam" not in wide:
                continue
            pair = wide[["medsam", m]].dropna()
            a, b = pair["medsam"].to_numpy(), pair[m].to_numpy()
            if len(a) == 0:
                continue
            try:
                p_val = float(wilcoxon(a, b, zero_method="wilcox", alternative="two-sided").pvalue)
            except ValueError:  # all paired differences are zero
                p_val = 1.0
            pooled.append({"metric": metric, "method": m, "ref_method": "medsam", "n_pairs": len(a),
                           "median_diff_medsam_minus_method": round(float(np.median(a - b)), 4),
                           "p_value": round(p_val, 4)})
    pooled = pd.DataFrame(pooled, columns=["metric", "method", "ref_method", "n_pairs",
                                           "median_diff_medsam_minus_method", "p_value"])
    pooled.to_csv(TAB / "wilcoxon_pooled.csv", index=False)
    parts += ["", "## 3b. Pooled Wilcoxon signed-rank tests (all 11 test volumes: 4 liver + 4 tumor + 3 prostate)"]
    for metric in ["dsc3d", "nsd3d"]:
        sub = pooled[pooled.metric == metric].drop(columns="metric")
        parts += ["", f"**{metric}** (two-sided, paired by volume; median diff = medsam minus method):",
                  md(sub) if len(sub) else "No pairs available."]
    parts += ["", "Per-target tests have only 3-4 pairs, so the pooled tests are the primary significance evidence."]

    # 3c. cross-task generalization of specialist baselines (median 3D DSC, jitter 0)
    ct_rows = []
    for m in ["unet", "deeplab", "medsam"]:
        row = {"method": m}
        for tgt, ct_tag in [("liver", "crosstask_from_prostate"), ("prostate", "crosstask_from_liver")]:
            ind = df[(df.method == m) & (df.target == tgt) & (df.tag == "") & (df.jitter == 0)].dsc3d.median()
            if m == "medsam":  # zero-shot: no training, so both columns are the same value
                cross = ind
            else:
                cross = df[(df.method == m) & (df.target == tgt) & (df.tag == ct_tag)].dsc3d.median()
            row[f"{tgt} in-distribution DSC"] = ind
            row[f"{tgt} cross-task DSC"] = cross
            row[f"{tgt} drop"] = ind - cross
        ct_rows.append(row)
    ct = pd.DataFrame(ct_rows).round(3)
    ct.to_csv(TAB / "crosstask.csv", index=False)
    parts += ["", "## 3c. Cross-task generalization of specialist baselines (median 3D DSC)",
              md(ct), "",
              "Cross-task = trained on the other task (liver target column uses the prostate-trained model; "
              "prostate target column uses the liver-trained model). MedSAM is zero-shot, so its two columns are identical by construction."]

    # 4. jitter ablation
    j = df[df.method.isin(["sam", "medsam"]) & df.tag.isin(["", "jitter"])]
    j = j[(j.tag == "jitter") | (j.jitter == 0)]
    parts += ["", "## 4. Box-jitter ablation (median 3D DSC per jitter level, px in 1024 space)"]
    if len(j):
        jt = j.groupby(["task", "target", "jitter", "method"]).dsc3d.median().unstack("method").reset_index()
        jt.columns.name = None
        parts.append(md(jt.round(3)))
        pt = df[(df.method == "medsam_point") & (df.tag == "")]
        for (t, g), s in pt.groupby(["task", "target"]):
            parts.append(f"- medsam_point (center point, label 1) {t}/{g}: median 3D DSC {s.dsc3d.median():.3f}")
    else:
        parts.append("No jitter rows.")

    # 5. sparse 3D
    parts += ["", "## 5. Sparse 3D propagation (k = every k-th foreground slice boxed)"]
    sp = TAB / "sparse3d.csv"
    if sp.exists():
        s = pd.read_csv(sp)
        sg = s.groupby(["task", "target", "k"]).agg(
            n_volumes=("volume", "nunique"), median_dsc3d=("dsc3d", "median"), median_nsd3d=("nsd3d", "median"),
            median_seconds=("seconds", "median"), median_n_boxes=("n_boxes", "median")).reset_index()
        parts.append(md(sg.round(3)))
    else:
        parts.append("sparse3d.csv missing.")

    # 6. training summaries
    parts += ["", "## 6. Training summaries"]
    tj = sorted(TAB.glob("train_*.json"))
    if not tj:
        parts.append("No train_*.json found.")
    for p in tj:
        with open(p, encoding="utf-8") as f:
            d = json.load(f)
        kv = [{"key": k, "value": json.dumps(v) if isinstance(v, (dict, list)) else v} for k, v in d.items()]
        parts += ["", f"### {p.name}", md(pd.DataFrame(kv))]

    lo = []
    for p in sorted(TAB.glob("train_lora_*.json")):
        with open(p, encoding="utf-8") as f:
            lo.append(json.load(f))
    if lo:
        tp, tot = lo[0]["trainable_params"], lo[0]["total_params"]
        vram = max(d["peak_vram_mb"] for d in lo) / 1000
        steps = ", ".join(f"{d['task']}/{d['target']} {d['optimizer_steps']}" for d in lo)
        mins = sum(d["train_seconds"] for d in lo) / len(lo) / 60
        parts += ["", f"**LoRA summary (from train_lora_*.json):** trainable params {tp:,} of {tot:,} "
                      f"({100 * tp / tot:.1f}%); mask decoder ~4.06M + LoRA matrices ~0.15M "
                      f"(static breakdown, not stored in the JSON); peak VRAM {vram:.1f} GB; "
                      f"optimizer steps {steps} (batch {lo[0]['bs']} x accum {lo[0]['accum']}); "
                      f"~{mins:.0f} min per target (mean)."]

    # 7. figures
    parts += ["", "## 7. Figures (results/figures)"]
    figs = sorted(FIG.glob("*.png")) if FIG.exists() else []
    parts += [f"- `results/figures/{f.name}`" for f in figs] or ["No figures yet."]

    # 8. decisions
    hand = (ROOT / "HANDOFF.md").read_text(encoding="utf-8")
    m = re.search(r"## 3\. Scope decisions[^\n]*\n(.*?)\n## 4\.", hand, re.S)
    parts += ["", "## 8. Decisions (copied from HANDOFF.md section 3)", m.group(1).strip() if m else "HANDOFF section 3 not found."]

    out = ROOT / "results/REPORT.md"
    out.write_text("\n".join(parts) + "\n", encoding="utf-8")
    log(f"wrote {out.name}: {len(rows)} summary rows, {len(wil)} wilcoxon rows, {len(figs)} figures")
    print("wrote", out)


if __name__ == "__main__":
    main()
